export function calculateScaledScores(scores: { listening: number; structure: number; reading: number }) {
  const getScaled = (raw: number, table: typeof SCORE_CONVERSION_TABLE.listening) => {
    const entry = table.find((r) => raw >= r.minRaw && raw <= r.maxRaw);
    return entry ? { min: entry.scaledMin, max: entry.scaledMax } : { min: 20, max: 24 };
  };

  const lScaled = getScaled(scores.listening, SCORE_CONVERSION_TABLE.listening);
  const sScaled = getScaled(scores.structure, SCORE_CONVERSION_TABLE.structure);
  const rScaled = getScaled(scores.reading, SCORE_CONVERSION_TABLE.reading);

  const totalMin = Math.round(((lScaled.min + sScaled.min + rScaled.min) * 10) / 3);
  const totalMax = Math.round(((lScaled.max + sScaled.max + rScaled.max) * 10) / 3);

  return {
    listening: `${lScaled.min}–${lScaled.max}`,
    structure: `${sScaled.min}–${sScaled.max}`,
    reading: `${rScaled.min}–${rScaled.max}`,
    total: `${totalMin}–${totalMax}`,
  };
}

